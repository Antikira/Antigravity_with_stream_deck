"""Tests for streamdeck_bridge entry points and graceful shutdown handling."""

import asyncio
from unittest.mock import patch

from src.antigravity_monitor.streamdeck_bridge import async_main, main


def test_async_main_standalone_cleanup_on_cancelled():
    """Verify collector.stop() and server.shutdown() are called on asyncio.CancelledError."""

    async def _test():
        class FakeArgs:
            port = None
            pluginUUID = None
            registerEvent = None
            info = None
            server_port = 18500

        mock_bridge = patch("src.antigravity_monitor.streamdeck_bridge.StreamDeckBridge").start()
        mock_server = patch(
            "src.antigravity_monitor.streamdeck_bridge.run_simulator_server"
        ).start()
        patch(
            "src.antigravity_monitor.streamdeck_bridge.parse_cli_args", return_value=FakeArgs()
        ).start()
        patch("asyncio.sleep", side_effect=asyncio.CancelledError()).start()

        try:
            await async_main()
            mock_bridge.return_value.collector.stop.assert_called_once()
            mock_server.return_value.shutdown.assert_called_once()
        finally:
            patch.stopall()

    asyncio.run(_test())


