def test_main_calls_async_main():
    """Verify synchronous main() invokes async_main() via asyncio.run()."""
    with (
        patch("src.antigravity_monitor.streamdeck_bridge.async_main") as mock_async_main,
        patch("asyncio.run") as mock_run,
    ):
        main()
        mock_run.assert_called_once()
        mock_async_main.assert_called_once()
        # Close the unawaited coroutine generated by mock_async_main
        coro = mock_run.call_args[0][0]
        coro.close()
